import type {
  Annotations,
  Generator,
  ResolvedDatabase,
} from "@opentyped/odb-db";

/** Runtime facts about one table or view, for crud and other generic code. */
export interface TableInfo {
  schema: string;
  name: string;
  kind: "table" | "view" | "materializedView" | "foreignTable";
  primaryKey: readonly string[];
  columns: readonly ColumnInfo[];
}

export interface ColumnInfo {
  name: string;
  /** SQL type name, e.g. `TEXT`, `int4`, or a domain/enum name. */
  type: string;
  nullable: boolean;
  primaryKey: boolean;
  generated: boolean;
  /** True when inserts may omit the column (default, identity, or generated). */
  optional: boolean;
  /** Constraints read from the schema, e.g. `{ maxLength: 200 }`. */
  annotations: Annotations;
}

/** An odb generator for `tables.ts`: a runtime map of every table's columns, keyed like Kysely's `Database`. */
export function tables(options: { file: string }): Generator {
  return {
    name: "framestack:tables",
    files: { declarations: options.file },
    generate(database: ResolvedDatabase) {
      const types = new Map(database.types.map((type) => [type.id, type.name]));

      const info = Object.fromEntries(
        database.relations.map((relation) => [
          relation.key,
          {
            schema: relation.schema,
            name: relation.name,
            kind: relation.kind,
            primaryKey: relation.columns
              .filter((column) => column.primaryKey)
              .map((column) => column.name),
            columns: relation.columns.map((column) => ({
              name: column.name,
              type: types.get(column.type) ?? column.type,
              nullable: column.nullable,
              primaryKey: column.primaryKey,
              generated: column.generated,
              optional: column.insertOptional,
              annotations: column.annotations,
            })),
          } satisfies TableInfo,
        ]),
      );

      return {
        files: {
          [options.file]: `// @generated by framestack generate. Do not edit.
import type { TableInfo } from "@opentyped/framestack-kysely-db/tables";

export const tables = ${JSON.stringify(info, null, 2)} as const satisfies Record<string, TableInfo>;
`,
        },
      };
    },
  };
}
